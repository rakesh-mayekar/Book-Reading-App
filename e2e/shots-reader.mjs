import { chromium } from 'playwright-core';
const BASE = process.env.BASE ?? 'http://127.0.0.1:5173';
const OUT = '/private/tmp/claude-501/shots';
const b = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
await ctx.addInitScript(() => sessionStorage.setItem('br-splash-seen', '1'));
const p = await ctx.newPage();
const errs = []; p.on('pageerror', (e) => errs.push(String(e)));
await p.goto(BASE + '/welcome');
await p.getByRole('button', { name: 'Skip' }).click();
await p.getByRole('button', { name: 'Drama' }).click(); await p.getByRole('button', { name: 'Mystery' }).click();
await p.getByRole('button', { name: 'Continue' }).click();
await p.getByRole('button', { name: 'English' }).click(); await p.getByRole('button', { name: 'Explore stories' }).click();
await p.waitForURL('**/discover'); await p.waitForTimeout(500);
await p.screenshot({ path: `${OUT}/R1-discover.png` });
await p.evaluate(() => (document.querySelector('main.scroll').scrollTop = 560)); await p.waitForTimeout(200);
await p.screenshot({ path: `${OUT}/R1b-discover-scrolled.png` });
await p.goto(BASE + '/story/story-last-train'); await p.waitForTimeout(400);
await p.screenshot({ path: `${OUT}/R2-details.png` });
await p.goto(BASE + '/read/story-last-train/1'); await p.waitForTimeout(500);
await p.screenshot({ path: `${OUT}/R3-reader.png` });
await p.getByRole('button', { name: 'Text size and theme' }).click(); await p.waitForTimeout(300);
await p.screenshot({ path: `${OUT}/R3b-reader-prefs.png` });
await p.getByRole('button', { name: 'Back to story' }).click();
await p.goto(BASE + '/story/story-last-train/contents'); await p.waitForTimeout(300);
await p.screenshot({ path: `${OUT}/R4-contents.png` });
await p.goto(BASE + '/discover'); await p.waitForTimeout(300);
await p.getByRole('button', { name: 'Save The Unsent Page' }).first().click();
await p.goto(BASE + '/library'); await p.waitForTimeout(300);
await p.screenshot({ path: `${OUT}/R5-library.png` });
console.log('errors', errs);
await b.close();
