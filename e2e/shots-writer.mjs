import { chromium } from 'playwright-core';
const BASE = process.env.BASE ?? 'http://127.0.0.1:5173';
const OUT = '/private/tmp/claude-501/shots';
const b = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
await ctx.addInitScript(() => sessionStorage.setItem('br-splash-seen', '1'));
const p = await ctx.newPage();
const errs = []; p.on('pageerror', (e) => errs.push(String(e)));
await p.goto(BASE + '/profile/demo'); await p.getByRole('button', { name: /Mira Sen/ }).first().click(); await p.waitForTimeout(300);
await p.goto(BASE + '/writer/dashboard'); await p.waitForTimeout(300); await p.screenshot({ path: `${OUT}/W1-desk.png` });
await p.goto(BASE + '/profile/writer'); await p.waitForTimeout(300); await p.screenshot({ path: `${OUT}/W2-profile.png` });
await p.goto(BASE + '/writer/story/new'); await p.waitForTimeout(300);
await p.getByLabel('Story title').fill('The House of Small Things');
await p.getByLabel('Synopsis').fill('When Leela inherits a house on a rain-soaked lane, every object inside seems to be waiting for someone to return.');
await p.getByLabel('Genre').selectOption('Drama'); await p.getByLabel('Story language').selectOption('English');
await p.screenshot({ path: `${OUT}/W3-setup.png` });
await p.getByRole('button', { name: 'Save & add chapters' }).click(); await p.waitForURL('**/chapters'); await p.waitForTimeout(300);
await p.getByRole('button', { name: 'Add a chapter' }).click(); await p.waitForURL('**/chapter/*'); await p.waitForTimeout(300);
await p.screenshot({ path: `${OUT}/W4-editor-empty.png` });
await p.getByLabel('Chapter title').fill('A key in the rain');
await p.getByLabel('Chapter text').fill('The key arrived on a Thursday, wrapped in a handkerchief Leela recognised before she recognised the handwriting.\n\nFor years, she had remembered the house as a collection of small sounds: the gate that never quite closed, a spoon against a glass.');
await p.getByLabel('Chapter text').selectText();
await p.getByRole('button', { name: 'Italic' }).click();
await p.waitForTimeout(1200); await p.screenshot({ path: `${OUT}/W5-editor.png` });
await p.getByRole('button', { name: 'Back' }).click(); await p.waitForURL('**/chapters'); await p.waitForTimeout(300);
await p.screenshot({ path: `${OUT}/W6-chapters.png` });
await p.getByRole('link', { name: 'Preview story' }).click(); await p.waitForTimeout(300); await p.screenshot({ path: `${OUT}/W7-preview.png` });
await p.getByRole('link', { name: 'Review for publishing' }).click(); await p.waitForTimeout(300); await p.screenshot({ path: `${OUT}/W8-publish.png` });
await p.getByText('I confirm I have the rights').click(); await p.waitForTimeout(150); await p.screenshot({ path: `${OUT}/W8b-publish-confirmed.png` });
await p.getByRole('button', { name: 'Publish story' }).click(); await p.waitForTimeout(400); await p.screenshot({ path: `${OUT}/W9-live.png` });
console.log('errors', errs);
await b.close();
